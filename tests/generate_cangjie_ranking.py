#!/usr/bin/env python3
"""Generate mobile Cangjie rank tables from the shared 1,500-character source."""
import argparse
import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "DataSource/AISyntheticBigram/common-single-character-pronunciations-1500.tsv"

def outputs():
    with SOURCE.open(encoding="utf-8") as stream:
        rows = sorted(csv.DictReader(stream, delimiter="\t"), key=lambda row: int(row["排名"]))
    assert len(rows) == 1500
    assert [int(row["排名"]) for row in rows] == list(range(1, 1501))
    characters = "".join(row["單字"] for row in rows)
    assert len(set(characters)) == len(characters) == 1500
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    header = "// Generated by tests/generate_cangjie_ranking.py; do not edit.\n"
    header += "// Source: DataSource/AISyntheticBigram/common-single-character-pronunciations-1500.tsv\n"
    header += "// Source SHA-256: " + digest + "\n"
    swift = header + """enum CangjieCommonRanking {
    static let characters = "%s"
    static let ranks: [String: Int] = Dictionary(uniqueKeysWithValues:
        characters.enumerated().map { (String($0.element), $0.offset + 1) })
}
""" % characters
    java = header + """package tw.chichi77.keykey.android;

import java.text.Normalizer;
import java.util.HashMap;
import java.util.Map;

final class CangjieCommonRanking {
    static final String CHARACTERS = "%s";
    static final Map<String, Integer> RANKS = ranks();
    static String identity(String text) { return Normalizer.normalize(text, Normalizer.Form.NFC); }
    static int rank(String text) { return RANKS.getOrDefault(identity(text), Integer.MAX_VALUE); }
    private static Map<String, Integer> ranks() {
        Map<String, Integer> result = new HashMap<>();
        int rank = 1;
        for (int offset = 0; offset < CHARACTERS.length();) {
            int cp = CHARACTERS.codePointAt(offset);
            result.put(new String(Character.toChars(cp)), rank++);
            offset += Character.charCount(cp);
        }
        return Map.copyOf(result);
    }
    private CangjieCommonRanking() {}
}
""" % characters
    return {
        ROOT / "Source/Loaders/iOS-Keyboard/KeyKeyEngine/Sources/KeyKeyEngine/CangjieCommonRanking.swift": swift,
        ROOT / "Source/Loaders/Android-IME/app/src/main/java/tw/chichi77/keykey/android/CangjieCommonRanking.java": java,
    }

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit("Stale Cangjie ranking: " + str(path))
        else:
            path.write_text(text, encoding="utf-8")
    print("Cangjie ranking: 1,500 unique characters; Swift/Java agree.")

if __name__ == "__main__":
    main()
