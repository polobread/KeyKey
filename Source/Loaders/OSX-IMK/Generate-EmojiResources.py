#!/usr/bin/env python3
"""Generate the macOS Emoji list from the same two inputs used by Windows."""
import argparse
import json
from pathlib import Path
import re

LOADER = Path(__file__).resolve().parent
ROOT = LOADER.parents[2]

def windows_emojis():
    swift = (ROOT / "Source/Loaders/iOS-Keyboard/KeyKeyEngine/Sources/KeyKeyEngine/BopomofoEngine.swift").read_text()
    match = re.search(r"public static let emojis: \[String\] = \[(.*?)\]", swift, re.S)
    if not match:
        raise ValueError("Mobile emoji declaration not found")
    block = match.group(1)
    mobile = re.findall(r'"([^"\\]*)"', block)
    if re.sub(r'"([^"\\]*)"|\s|,', '', block) or len(mobile) != 90 or len(set(mobile)) != 90:
        raise ValueError("Expected the same 90 unescaped mobile emoji strings as Windows")
    supplement = json.loads((ROOT / "Source/Loaders/Windows-TSF/SymbolEmojiSupplement.json").read_text())
    if len(supplement) != 110 or any(not isinstance(item, str) or not item for item in supplement):
        raise ValueError("Expected the same 110 supplementary emoji strings as Windows")
    emojis = mobile + supplement
    if len(set(emojis)) != 200:
        raise ValueError("Expected 200 unique Emoji strings")
    return emojis

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json-output", type=Path, help="Write reference strings for the isolated native test")
    args = parser.parse_args()
    emojis = windows_emojis()
    lines = ["// Generated by Generate-EmojiResources.py. Do not edit.",
             "// Sources match Windows Generate-SymbolResources.ps1: mobile 90 + supplement 110.",
             "#pragma once", "static NSArray *CVBuiltinEmojis(void) {", "    return @["]
    lines += ["        @" + json.dumps(emoji, ensure_ascii=False) + "," for emoji in emojis]
    lines += ["    ];", "}", ""]
    content = "\n".join(lines)
    output = LOADER / "CVEmojiData.generated.h"
    if args.check:
        if not output.exists() or output.read_text() != content:
            raise SystemExit("macOS Emoji list is stale; run Generate-EmojiResources.py")
    else:
        output.write_text(content)
    if args.json_output:
        args.json_output.write_text(json.dumps(emojis, ensure_ascii=False))

if __name__ == "__main__":
    main()
