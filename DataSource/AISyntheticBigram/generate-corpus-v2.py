def main():
    output = Path(__file__).with_name("corpus-v2.txt")
    lines = []
    sentences = []

    for title, beginnings, endings in SECTIONS:
        if len(beginnings) != 5 or len(endings) != 5:
            raise ValueError(f"{title}: every section must contain five beginnings and endings")
        lines.append(f"# {title}")
        # Latin-square ordering keeps the same beginning or ending from forming
        # a visible block while still covering every one of the 25 pairings.
        for offset in range(5):
            for index, beginning in enumerate(beginnings):
                ending = endings[(index + offset) % 5]
                sentence = f"{beginning} {ending}"
                han_length = len(re.findall(r"[\u3400-\u9fff]", sentence))
                if not 8 <= han_length <= 30:
                    raise ValueError(f"{title}: sentence length {han_length}: {sentence}")
                sentences.append(sentence)
                lines.append(sentence)
        lines.append("")

    if len(SECTIONS) != 40 or len(sentences) != 1_000:
        raise ValueError(f"expected 40 sections and 1000 sentences, got {len(SECTIONS)} and {len(sentences)}")
    if len(set(sentences)) != len(sentences):
        raise ValueError("generated corpus contains duplicate sentences")

    output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {len(sentences)} unique sentences to {output}")


if __name__ == "__main__":
    main()
